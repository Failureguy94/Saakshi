# CLI
# ──────────────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Validate Saakshi recovery against synthetic ground truth."
    )
    parser.add_argument(
        "disk_image",
        type=Path,
        help="Path to synthetic_dvr.img",
    )
    parser.add_argument(
        "ground_truth",
        type=Path,
        help="Path to ground_truth.json",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("docs/validation"),
        help="Directory for JSON report (default: docs/validation/)",
    )
    parser.add_argument(
        "--min-confidence",
        type=float,
        default=0.0,
        help="Discard recovered segments below this confidence score (0.0 = keep all)",
    )
    parser.add_argument(
        "--no-repair",
        action="store_true",
        help="Skip GOP repair pass",
    )
    args = parser.parse_args()

    result = run_validation(
        disk_image=args.disk_image,
        ground_truth=args.ground_truth,
        out_dir=args.out_dir,
        min_confidence=args.min_confidence,
        run_repair=not args.no_repair,
    )
    _print_table(result)
    report_path = list(args.out_dir.glob("synthetic_validation_*.json"))
    if report_path:
        print(f"Report written to: {sorted(report_path)[-1]}")


if __name__ == "__main__":
    main()
