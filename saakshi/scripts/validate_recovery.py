def _print_table(result: dict[str, Any]) -> None:
    m = result["metrics"]
    cs = result["carver_stats"]
    rm = result["run_metadata"]

    print()
    print("=" * 60)
    print("  SAAKSHI RECOVERY VALIDATION REPORT (SYNTHETIC DATA)")
    print("=" * 60)
    print(f"  ⚠  {rm['warning'][:60]}")
    print(f"     (see docs/validation/validation-plan.md)")
    print("-" * 60)
    print(f"  Disk image        : {Path(rm['disk_image']).name}")
    print(f"  Ground-truth clips: {rm['gt_total_clips']}  "
          f"(evaluable: {rm['gt_evaluable_clips']}, deleted: {rm['gt_deleted_clips']})")
    print(f"  NAL units carved  : {cs['nal_units_carved']}")
    print(f"  Segments (pre-repair) : {cs['pre_repair_segments']}")
    print(f"  Segments repaired : {cs['repaired_segments']}")
    print(f"  Segments (final)  : {cs['final_segments']}")
    print("-" * 60)
    print(f"  Precision         : {m['precision']:.1%}")
    print(f"  Recall            : {m['recall']:.1%}")
    print(f"  F1                : {m['f1']:.1%}")
    print(f"  Byte recovery rate: {m['byte_recovery_rate']:.1%}")
    print("-" * 60)
    print(f"  Exact matches     : {m['exact_matches']}")
    print(f"  Partial matches   : {m['partial_matches']}")
    print(f"  Missed            : {m['missed']}")
    print(f"  False positives   : {m['false_positives']}")
    print("=" * 60)
    print()


